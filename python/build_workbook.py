last_d = write_df("Deposits", deposits, {"deposit_datetime": DT, "amount": M}, {"deposit_datetime": 22})
last_b = write_df("Bets", bets, {"bet_datetime": DT, "stake": M, "payout": M}, {"bet_datetime": 22})

