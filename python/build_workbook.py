"""
build_workbook.py -- packages the 3 CSVs into one Excel workbook (for viewing / sharing).
Run AFTER generate_igaming_data.py.   The CSVs stay the source of truth for SQL.

Sheets: README | Data Dictionary | Checks | Players | Deposits | Bets
The 'Checks' sheet uses LIVE Excel formulas where Excel can do the job (counts, sums, GGR, RTP).
Join checks (orphans, dates) are computed in Python because they are too heavy for Excel; they are
shown as blue hard-coded values and labelled as such.
"""
