# ---------------- data sheets ----------------
def write_df(name, df, fmts, widths):
    s = wb.create_sheet(name)
    s.append(list(df.columns))
    for rec in df.itertuples(index=False):
        s.append([v.to_pydatetime() if isinstance(v, pd.Timestamp) else v for v in rec])
    for j, col in enumerate(df.columns, 1):
        letter = get_column_letter(j)
        s.column_dimensions[letter].width = widths.get(col, 16)
        hc = s.cell(row=1, column=j)
        hc.font, hc.fill = HEAD_FONT, HEAD_FILL
        fmt = fmts.get(col)
        for r in range(2, len(df) + 2):
            c = s.cell(row=r, column=j)
            c.font = F()
            if fmt:
                c.number_format = fmt
    s.freeze_panes = "A2"
    s.auto_filter.ref = s.dimensions
    return len(df) + 1          # last row number

